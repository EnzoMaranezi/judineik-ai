interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, vars?: TranslationVars) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && SUPPORTED_LOCALES.includes(value as Locale);
}

export function getUserLocale(userMetadata: Record<string, unknown> | undefined): Locale {
  const locale = userMetadata?.["locale"];
  return isLocale(locale) ? locale : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const { user } = useAuth();
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    if (user) setLocale(getUserLocale(user.user_metadata));
  }, [user]);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = locale;
    }
  }, [locale]);

  return (
    <I18nContext.Provider
      value={{ locale, setLocale, t: (key, vars) => translate(locale, key, vars) }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function translate(locale: Locale, key: TranslationKey, vars: TranslationVars = {}) {
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  return Object.entries(vars).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

